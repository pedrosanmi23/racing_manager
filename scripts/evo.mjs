p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('file:///home/user/campeonatos/app/dist/index.html');
await p.click('text=Cargar demo');
await p.click('.tile');
await p.click('text=Campeonato de Monoplazas');
await p.click('tr:has-text("2026")');
await p.click('.tabs a[href$="/evolucion"]');
const box = await p.locator('.chart svg').boundingBox();
await p.mouse.move(box.x + box.width * 0.55, box.y + 150);
await p.screenshot({ path: '/home/user/shots/evo1.png' });
await p.click('text=Posición en el campeonato');
await p.locator('.chip').nth(0).click();
await p.mouse.move(box.x + box.width * 0.3, box.y + 150);
await p.screenshot({ path: '/home/user/shots/evo2.png' });
console.log('errores', errs);
await b.close();
